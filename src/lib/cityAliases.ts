/**
 * Tenta resolver um nome digitado em PT-BR para o nome internacional.
 * Retorna o termo traduzido ou o original se não houver alias.
 */
export function resolveSearchTerm(input: string): string {
  const normalized = input
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim();

  // Try exact match first
  if (ptBrCityAliases[normalized]) return ptBrCityAliases[normalized];

  // Try with accents preserved
  const withAccents = input.toLowerCase().trim();
  if (ptBrCityAliases[withAccents]) return ptBrCityAliases[withAccents];

  return input;
}
